"""Record a live run as evidence: row growth, a zone window filling up, and end-to-end latency.

Watches the database (DATABASE_URL) while the real pipeline runs, samples every INTERVAL seconds
for DURATION seconds, then writes docs/live_demo.md. Nothing is simulated: the numbers come from
the producer, the Kafka broker and the consumers that are running at the time.

Latency is measured per trip as ingested_at - event_time:
  event_time   set by the producer when it creates the trip,
  ingested_at  set by Postgres when the storage consumer inserts the row.
That covers producer -> Kafka -> consumer -> database. The dashboard adds up to one refresh
interval (5 s) plus its 4 s query cache before a row is on screen. Both clocks are NTP-synced
machines (your Docker VM and the database server); a small skew shifts every value equally.

Run (no local Python needed):
  docker compose --profile apps build
  docker compose --profile apps run --rm -v "$PWD/docs:/app/docs" producer python scripts/live_demo_check.py
Options: DURATION=300 INTERVAL=30 (environment variables, in seconds)
"""

import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common.db import connect  # noqa: E402

DURATION = int(os.getenv("DURATION", "300"))
INTERVAL = int(os.getenv("INTERVAL", "30"))
OUT = Path(__file__).resolve().parents[1] / "docs" / "live_demo.md"
ET = ZoneInfo("America/New_York")


def et(ts: datetime) -> str:
    return ts.astimezone(ET).strftime("%Y-%m-%d %H:%M:%S %Z")


def main():
    conn = connect()
    conn.autocommit = True
    q = lambda sql, *a: conn.execute(sql, a).fetchall()  # noqa: E731

    started = datetime.now(timezone.utc)
    samples = []
    print(f"watching for {DURATION} s, sampling every {INTERVAL} s...")
    while True:
        now = datetime.now(timezone.utc)
        (n, last), = q("SELECT count(*), max(event_time) FROM trips")
        (alerts,), = q("SELECT count(*) FROM surge_alerts")
        samples.append((now, n, last, alerts))
        print(f"{et(now)}  trips={n}  alerts={alerts}")
        if (now - started).total_seconds() >= DURATION:
            break
        time.sleep(INTERVAL)
    ended = samples[-1][0]

    # A window that was open during the run: its trip count as seen at each sample is not stored,
    # so read the busiest window of the run and its last update time instead.
    window = q("""SELECT window_start, pickup_zone, trips, cancelled, round(avg_surge::numeric, 2), updated_at
                  FROM zone_minute_metrics WHERE window_start >= %s
                  ORDER BY trips DESC LIMIT 1""", started.replace(second=0, microsecond=0))
    lat = q("""SELECT percentile_cont(ARRAY[0.5, 0.95]) WITHIN GROUP
                      (ORDER BY extract(epoch FROM ingested_at - event_time)), count(*)
               FROM trips WHERE ingested_at BETWEEN %s AND %s""", started, ended)
    trace = q("""SELECT trip_id, pickup_zone, status, event_time, ingested_at
                 FROM trips WHERE ingested_at BETWEEN %s AND %s
                 ORDER BY ingested_at DESC LIMIT 1""", started, ended)
    run_alerts = q("""SELECT window_start, message FROM surge_alerts
                      WHERE alerted_at BETWEEN %s AND %s ORDER BY window_start""", started, ended)

    first, last = samples[0], samples[-1]
    lines = [
        "# Live demo record",
        "",
        f"Generated by `scripts/live_demo_check.py` against the running pipeline "
        f"(real Kafka broker, database host `{conn.info.host}`).",
        "",
        f"* Run: {et(started)} to {et(ended)} ({(ended - started).total_seconds() / 60:.1f} min)",
        f"* `trips` rows: {first[1]:,} → {last[1]:,} (+{last[1] - first[1]:,}, "
        f"{(last[1] - first[1]) / max(1, (ended - started).total_seconds()):.2f} rows/s)",
        f"* Zone alerts fired during the run: {len(run_alerts)}",
        "",
        "## Row count over the run",
        "",
        "| Time (ET) | trips rows | alerts rows | newest event_time (ET) |",
        "|---|---|---|---|",
        *[f"| {et(t)[11:19]} | {n:,} | {a:,} | {et(lv)[11:19] if lv else '-'} |" for t, n, lv, a in samples],
        "",
        "## End-to-end latency (producer → Kafka → consumer → Postgres)",
        "",
    ]
    if lat and lat[0][1]:
        (p50, p95), count = lat[0][0], lat[0][1]
        lines += [
            f"Over {count:,} trips inserted during the run: median **{p50:.2f} s**, 95th percentile "
            f"**{p95:.2f} s** (`ingested_at - event_time`). The storage consumer batches for up to "
            "1 s, which is most of that. The dashboard then shows a row within one 5 s refresh "
            "(plus a 4 s query cache).",
            "",
        ]
    if trace:
        tid, zone, status, ev, ing = trace[0]
        lines += [
            f"Traced trip: `{tid}` ({zone}, {status}) — created {et(ev)}, stored {et(ing)}, "
            f"{(ing - ev).total_seconds():.2f} s later.",
            "",
        ]
    if window:
        ws, zone, trips, cancelled, surge, upd = window[0]
        lines += [
            "## A one-minute window from the stream processor",
            "",
            f"Busiest window of the run: **{zone}**, minute starting {et(ws)[11:16]} ET — "
            f"{trips} trips, {cancelled} cancelled, average surge {surge}×, last updated "
            f"{et(upd)[11:19]} ET (`zone_minute_metrics`).",
            "",
        ]
    if run_alerts:
        lines += ["## Alerts fired during the run", "",
                  *[f"* {et(w)[11:16]} ET — {m}" for w, m in run_alerts], ""]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
